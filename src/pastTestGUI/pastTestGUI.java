    // Method that displays the search results
    public void pageDisplay(){
        // Sets the visibility of all the panels to false
        pnlTestResult1.setVisible(false);
        pnlTestResult2.setVisible(false);
        pnlTestResult3.setVisible(false);
        btnNextPage.setVisible(false);
        btnPreviousPage.setVisible(false);
        int intPagesDisplay;
        // Since each page can display up to 3 pages, the amount of pages is the results found/3 + 1 if there is a remainder
        int intPageAmount = arrayTestsFound.size()/3;
        if (arrayTestsFound.size()%3 != 0){
            intPageAmount += 1;
        }
        // Checks if the page amount is greater than 1, and that the page amount is not the last page
        if (intPageAmount > 1 && intPageAmount != intPageNum){
            // Displays button
            btnNextPage.setVisible(true);
        }
        // Checks if the current page is not the first page
        if (intPageNum != 1){
            // Displays previous page button
            btnPreviousPage.setVisible(true);
        }
        // Displays number of pages
        lblPages.setText("Pages: " + intPageAmount);
        // Checks how many panels need to be displayed if it is the final page
        if (intPageAmount == intPageNum){
            intPagesDisplay = (arrayTestsFound.size() - intPageAmount*3) + 3;
        }else{
            intPagesDisplay = 3;
        }
        // Displays first panel and sets the values
        if (intPagesDisplay >= 1){
            pnlTestResult1.setVisible(true);
            lblTestUnit1.setText((arrayTestsFound.get((intPageNum - 1)*3))[0]);
            lblTestName1.setText((arrayTestsFound.get((intPageNum - 1)*3))[2]);
            lblTeacherName1.setText("Teacher: " + (arrayTestsFound.get((intPageNum - 1)*3))[3]);
            lblTestResult1.setText("Result: " + (1 + (intPageNum - 1)*3));
        }
        // Displays second panel and sets the values
        if (intPagesDisplay >= 2){
            pnlTestResult2.setVisible(true);
            lblTestUnit2.setText((arrayTestsFound.get(1 + (intPageNum - 1)*3))[0]);
            lblTestName2.setText((arrayTestsFound.get(1 + (intPageNum - 1)*3))[2]);
            lblTeacherName2.setText("Teacher: " + (arrayTestsFound.get(1 + (intPageNum - 1)*3))[3]);
            lblTestResult2.setText("Result: " + ((2 + (intPageNum - 1)*3)));
        }
        // Displays third panel and sets the values
        if (intPagesDisplay == 3){
            pnlTestResult3.setVisible(true);
            lblTestUnit3.setText((arrayTestsFound.get(2 + (intPageNum - 1)*3))[0]);
            lblTestName3.setText((arrayTestsFound.get(2 + (intPageNum - 1)*3))[2]);
            lblTeacherName3.setText("Teacher: " + (arrayTestsFound.get(2 + (intPageNum - 1)*3))[3]);
            lblTestResult3.setText("Result: " + ((3 + (intPageNum - 1)*3)));
        }
        
    }
    
