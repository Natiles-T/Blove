    private void btnSearchTestActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchTestActionPerformed
        // Sets btnUpload to not visible
        btnUpload.setVisible(false);
        // Clears arrayTestsFound
        arrayTestsFound.clear();
        // Sets intPageNum equal to 1
        intPageNum = 1;
        // Gets user input
        String strUserSearch = txtSearchInput.getText();
        // Tries code and catches error
        try{
            // Instantiates buffered reader to read Tests.
            BufferedReader reader = new BufferedReader(new FileReader("src/pastTestGUI/Tests.txt"));
            String line;
            // While loop that goes through every line in the txt file until there is an empty line
            while((line = reader.readLine()) != null){
                // Splits the line whenever there is a colon found
                String[] arrayParts = line.split(":");
                // Checks if the user inputted anything simular to arrayParts[1]
                if((arrayParts[1].toLowerCase()).contains(strUserSearch.toLowerCase())){
                    // Adds it to the arrayTestsFound
                    arrayTestsFound.add(arrayParts);
                }
            }
            // Checks if the user found tests
            if(!arrayTestsFound.isEmpty()){
                // Displays results
                lblResults.setVisible(true);
                lblPages.setVisible(true);
                pageDisplay();
                lblResults.setText(Integer.toString(arrayTestsFound.size()));
            }else {
                // Prompts user to upload their own test
                pnlTestResult1.setVisible(true);
                pnlTestResult2.setVisible(false);
                pnlTestResult3.setVisible(false);
                lblTestUnit1.setText("Test not found");
                lblTestName1.setText("Upload your own test?");
                lblTeacherName1.setText("");
                lblTestResult1.setText("");
                btnUpload.setVisible(true);
            }
            // Catches errors when reading the file
        }catch(IOException e){
            // Displays that there was an error
            lblResults.setText("Results: An error has occured while accessing the file");
        }
    }//GEN-LAST:event_btnSearchTestActionPerformed

