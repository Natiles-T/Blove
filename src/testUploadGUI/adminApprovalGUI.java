    public void checkInfo(){
        // Tries code and catches errors
        try{
            // Instantiates BufferedReader that reads pending tests
            BufferedReader reader = new BufferedReader(new FileReader("src/testUploadGUI/PendingTests.txt"));
            String line;
            intPending = 0;
            // Reads first line and checks if it is not empty
            if ((line = reader.readLine()) != null){
                String[] arrayParts = line.split(":");
                // Sets each value to the class variables
                strCourse = arrayParts[0];
                strUnitNum = arrayParts[1];
                strTeacher = arrayParts[4];
                strUnitName = arrayParts[2];
                strAssessment = arrayParts[3];
                strPhotoLocations = arrayParts[5];
                // Adds 1 to represent the number of lines
                intPending += 1;
            }
            
            // Reads the rest of the txt file
            while((line = reader.readLine()) != null){
                // Adds 1 to intPending for each line
                intPending += 1;
            }
            // If there are no lines in the pending tests, it sets all class variables to null
            if (intPending == 0){
                strCourse = null;
                strUnitNum = null;
                strTeacher = null;
                strUnitName = null;
                strAssessment = null;
                strPhotoLocations = null;
            }
            // Displays number of tests
            lblPending.setText("Pending Tests: " + intPending);
            // Closes reader
            reader.close();
        // Catches errors
        }catch(IOException e){
            System.out.println("An error has occured while accessing the file");
        }
    }
    
    // BubbleSort method that returns a arraylist
    public ArrayList bubbleSort(ArrayList tests){
        // Sets intLength to the size of the arraylist
        int intLength = tests.size();
        // Initializes boolHasSwapped
        boolean boolHasSwapped;
        
        // For loop that goes through the length of the arraylist
        for(int i = 0; i < intLength - 1; i++){
            // Sets boolHasSwapped to false
            boolHasSwapped = false;
            // For loop that goes the length of the array list
            for(int m = 0; m < intLength - 1; m++){
                // Compares the current index to the next index and swaps them if the current is larger than the next
                if(String.valueOf(tests.get(m+1)).compareTo(String.valueOf(tests.get(m))) < 0){
                    String strTemporary = String.valueOf(tests.get(m+1));
                    tests.set(m+1, tests.get(m));
                    tests.set(m, strTemporary);
                    // Sets has swapped to true
                    boolHasSwapped = true;
                }
            }
            // Breaks the for loops if no swaps are made
            if(!boolHasSwapped){
                break;
            }
        }
        return tests;
    }
