    private void btnValidateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnValidateActionPerformed
        // Checks if all checkboxes are selected
        if (ckbxAssessment.isSelected() && ckbxCourse.isSelected() && ckbxTeacher.isSelected() && ckbxUnitName.isSelected() && ckbxUnitNum.isSelected()){
            // Tries code and catches error
            try{
                // Instantiates BufferedReader and allows it to read PendingTests
                BufferedReader pendingReader = new BufferedReader(new FileReader("src/testUploadGUI/PendingTests.txt"));
                // Creates 2 array lists that hold the lines in txt files
                ArrayList<String> testList = new ArrayList<>();
                ArrayList<String> pendingTestList = new ArrayList<>();
                String pendLine;
                // Goes through each line in PendingTests and adds it to the pendingTestList
                while((pendLine = pendingReader.readLine()) != null){
                    pendingTestList.add(pendLine);
                }
                // Removes the first value from the pendingTestList
                pendingTestList.remove(0);
                // Closes pendingReader
                pendingReader.close();

                // Instantiates BufferedWriter and lets it write to PendingTests
                BufferedWriter pendingWriter = new BufferedWriter(new FileWriter("src/testUploadGUI/PendingTests.txt"));

                // Writes every row from pendingTestList into the PendingTests
                for (String row: pendingTestList){
                    pendingWriter.write(row + "\n");
                }
                // Closes writer
                pendingWriter.close();

                // Instantiates Buffered Reader than reads Tests.txt
                BufferedReader reader = new BufferedReader(new FileReader("src/pastTestGUI/Tests.txt"));
                String line;
                // Goes through all lines and adds it to the array list
                while((line = reader.readLine()) != null){
                    testList.add(line);
                }
                // Closes reader
                reader.close();

                // Instantiates Buffered Writer
                BufferedWriter writer = new BufferedWriter(new FileWriter("src/pastTestGUI/Tests.txt"));
                // Adds the informations to the testList
                testList.add((strCourse + ": " + strCourse + " Unit " + strUnitNum + " Test " + strUnitName + " " + strAssessment + ":" + strAssessment + ":" + strTeacher + ":" + strPhotoLocations));
                // Uses bubbleSort method to sort testList
                testList = bubbleSort(testList);
                // Writes the sorted arraylist into the txt file
                for (String row: testList){
                    writer.write(row + "\n");
                }
                // Closes Writer
                writer.close();
                // Hides validation screen
                hideValidationScreen();
                // Checks info and updates pendingTests amount
                checkInfo();
                // Catchs IO Exception
            }catch(IOException e){
                e.printStackTrace();
                System.out.println("An error has occured while accessing the file");
            }
        }

    }//GEN-LAST:event_btnValidateActionPerformed

