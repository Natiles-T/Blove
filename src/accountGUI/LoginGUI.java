    public static int verifyLogin(String usrInput, String pswdInput) { // verifies login
        for (int i = 0; i < adminCodes.length; i++) { // checks for admin codes
            if (pswdInput.equals(adminCodes[i])) {
                admin = true;
                return 2; // admin success
            }
        }
        try (BufferedReader reader = new BufferedReader(new FileReader("userinfo.txt"))) { // initalizes buffer reader
                String line = reader.readLine();
                while (line != null) { 
                    String[] parts = line.split(","); // split at "," detected
                    if (parts[0].equals(usrInput) && parts[1].equals(pswdInput)) {  // check split parts, if usr and pswd match the entered values
                        return 1;
                    }
                    line = reader.readLine();
                }
            } catch (Exception e) { // catch exceptions if they appear
            }
        return 0; // send failure
    }
    
