    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        // Clears previous warnings
        lblWarning.setText("");
        int loginTrue = verifyLogin(txtUsername.getText(),String.valueOf(txtPassword.getPassword())); // sends a call to check if it's a valid login
        if (loginTrue == 2) {
            // admin success
            admin = true;
            
            MainGUI home = new MainGUI();
            
            home.setVisible(true);
            this.setVisible(false);
        }
        else if (loginTrue == 1) { // student success
            admin = false;
            try 
            {
                BufferedReader reader = new BufferedReader(new FileReader("userinfo.txt"));
                String line = reader.readLine();
                while (line != null) {
                    String[] parts = line.split(",");
                    user = new Student(parts[0], parts[1], Integer.valueOf(parts[2]), Integer.valueOf(parts[3]), Integer.valueOf(parts[4]), Boolean.valueOf(parts[5]), Boolean.valueOf(parts[6]));
                    line = reader.readLine();
                }
               reader.close();
            } 
            catch (Exception ex) 
            {
                
            }
            
            MainGUI home = new MainGUI();
            
            home.setVisible(true);
            this.setVisible(false);
        }
        else {
            admin = false;
            lblWarning.setText("Invalid Login! Please check your username/password.");
        }
        
    }//GEN-LAST:event_btnLoginActionPerformed

