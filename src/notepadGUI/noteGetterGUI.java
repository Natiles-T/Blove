    public void loadNotes(){
        DefaultListModel<String> listModel = new DefaultListModel<>(); /*Creates a list model that will hold the note names*/
        
        for (String note : storeNotes.userNotes.get(currentUsername)){ /*For every note name stored in the specific ArrayList associated with the key (username) of the user*/
            listModel.addElement(note); /*It prints out the name of the notes*/
        }
        
        if(listModel.size() == 0)
        {
            lblWarning.setText("No Notes found! Make a new note by clicking 'New Note'.");
        }
        
        notesList.setModel(listModel); /*Update GUI to display current user's notes*/
    }
    
