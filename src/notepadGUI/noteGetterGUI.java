    private void btnNewNoteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNewNoteActionPerformed
        if(LoginGUI.adminCheck())
        {
            notepadGUI newNote = new notepadGUI();

            newNote.setVisible(true);
            this.setVisible(false);
        }
        username = txtUsername.getText();
        String password = String.valueOf(txtPassword.getPassword());
        
        // Clears previous warnings
        lblWarning.setText("");
        
        int verification = LoginGUI.verifyLogin(username, password);
        if(verification == 0)
        {
            lblWarning.setText("Invalid login! Please check again.");
        }
        else
        {
            /*Need something overhere to store the logged in user */
        
            storeNotes.userNotes.putIfAbsent(username, new ArrayList<>());

            notepadGUI newNote = new notepadGUI();

            newNote.setVisible(true);
            this.setVisible(false);
        }
    }//GEN-LAST:event_btnNewNoteActionPerformed

    private void btnPastNotesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPastNotesActionPerformed
        if(LoginGUI.adminCheck())
        {
            lblWarning.setText("Admin detected; No notes stored with admin access.");
            return;
        }
        
        String username = txtUsername.getText(); /*Get the text from the inputed username*/
        String password = String.valueOf(txtPassword.getPassword()); /*Get the text from the inputed password*/
        
        // Clears previous warnings
        lblWarning.setText("");
        
        int verification = LoginGUI.verifyLogin(username, password);
        if(verification == 0)
        {
            lblWarning.setText("Invalid login! Please check again.");
        }
        else
        {
            currentUsername = username; /*If login succeeds, store the username*/
            storeNotes.userNotes.putIfAbsent(username, new ArrayList<>()); /*putIfAbsent is used to add a key-value pair (notes and isername) if the key (username) is not already present.
            Essentially, if the username doesn't have a list of notes associated with them already, a new ArrayList<>() is created.*/
            loadNotes(); /*Gets the list displayed on screen*/
        }
        
    }//GEN-LAST:event_btnPastNotesActionPerformed

